#!/usr/bin/env node
// b3-proposal-dryrun.js — a DRY RUN of the proposal step (B3 c) without creating the cron job.
//
// Reads journal/lessons.jsonl, writes proposals/<date>.md. It edits no rule file: applying a
// proposal stays a separate, user-approved step. This exists to show the shape of the pipeline the
// cron job would run, and to satisfy B3's "a dry run of sample lesson -> sample proposal".
const fs = require('fs');
const path = require('path');

const V2 = 'D:/code/orca-supervisor';
const LESSONS = path.join(V2, 'journal/lessons.jsonl');
const PROPOSALS = path.join(V2, 'proposals');

const journal = require('./journal.js');

// Effective status comes from the journal model, never from the record's own `status` field: that
// field is the seed value, and a status change is an APPENDED EVENT (src/journal.js). Reading the
// field directly is exactly the bug that made a simulation edit a record in place.
const { lessons, malformed, seeds, events } = journal.lessonsWithStatus();
const open = lessons.filter(l => l.status === 'proposed');
const lessons_count = lessons.length;

const date = new Date().toISOString().slice(0, 10);
const out = path.join(PROPOSALS, `${date}.md`);
fs.mkdirSync(PROPOSALS, { recursive: true });

const lines = [];
lines.push(`# Proposals — ${date} (dry run, not applied)`);
lines.push('');
lines.push(`Source: journal/lessons.jsonl — ${lessons_count} lesson(s), ${open.length} with effective status \`proposed\`.`);
lines.push('');
lines.push('This document proposes; it does not apply. Applying any item is a separate step that needs');
lines.push('the user\'s approval, and nothing here edits the runbook or any other rule file.');
lines.push('');
lines.push('Status is the EFFECTIVE status: the record\'s own `status` field is its seed value, and a change');
lines.push('is an appended `status_change` event. This run reads neither by hand — `src/journal.js` resolves it.');
lines.push('');
for (const [i, l] of open.entries()) {
  const r = l.record;
  lines.push(`## ${i + 1}. ${r.symptom}`);
  lines.push('');
  lines.push(`- **id** — \`${l.id}\` (derived from the symptom; ids are never stored, because storing one would be an edit)`);
  lines.push(`- **root cause** — ${r.root_cause}`);
  lines.push(`- **evidence** — ${r.evidence}`);
  lines.push(`- **proposed rule** — ${r.proposed_rule}`);
  lines.push(`- **target** — \`orca-sup-runbook\` (hard rules) — pinned and under \`skills.write_approval: true\`,`);
  lines.push(`  so applying it would stage for review rather than land.`);
  lines.push('');
}
lines.push('---');
lines.push('');
lines.push(`Generated by \`src/b3-proposal-dryrun.js\`. The scheduled equivalent is the \`sup-lessons-review\``);
lines.push('job, which is **not created** (B3 c needs explicit approval).');

fs.writeFileSync(out, lines.join('\n'));
console.log(`proposal written: ${out} (${fs.statSync(out).size} B)`);
console.log(`lessons: ${lessons_count} total, ${open.length} proposed (effective status)`);
console.log(`journal: ${seeds} seed record(s), ${events} status_change event(s), ${malformed.length} malformed`);
console.log('no rule file was touched.');
